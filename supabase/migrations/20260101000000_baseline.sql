AS $function$
  SELECT DISTINCT "eventType"::text AS event_type
  FROM "streamEvents"
  WHERE "eventType" IS NOT NULL
  ORDER BY event_type;
$function$
;

CREATE OR REPLACE FUNCTION public.get_user_leaderboard()
 RETURNS TABLE(login text, event_count bigint, message_count bigint, last_active timestamp with time zone, raid_count bigint, raid_total bigint, sub_count bigint, giftsub_count bigint, giftsub_total bigint, cheer_count bigint, cheer_total bigint)
 LANGUAGE sql
 STABLE SECURITY DEFINER
AS $function$
  SELECT
    e.login::text,
    COUNT(*)                                                                   AS event_count,
    COUNT(*) FILTER (WHERE e."eventType" = 'onChatMessage')                   AS message_count,
    MAX(e.created_at)                                                         AS last_active,
    COUNT(*) FILTER (WHERE e."eventType" = 'twitch:raid')                     AS raid_count,
    COALESCE(SUM(e.quantity) FILTER (WHERE e."eventType" = 'twitch:raid'), 0) AS raid_total,
    COUNT(*) FILTER (WHERE e."eventType" = 'twitch:sub')                      AS sub_count,
    COUNT(*) FILTER (WHERE e."eventType" = 'twitch:giftsub')                  AS giftsub_count,
    COALESCE(SUM(e.quantity) FILTER (WHERE e."eventType" = 'twitch:giftsub'), 0) AS giftsub_total,
    COUNT(*) FILTER (WHERE e."eventType" = 'twitch:cheer')                    AS cheer_count,
    COALESCE(SUM(e.quantity) FILTER (WHERE e."eventType" = 'twitch:cheer'), 0) AS cheer_total
  FROM "streamEvents" e
  WHERE e."eventType" NOT IN ('onJoin', 'onPart')
    AND e.login IS NOT NULL
  GROUP BY e.login;
$function$
;

