CREATE OR REPLACE FUNCTION public.compute_all_stream_stats()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
   DECLARE
     stream_rec RECORD;
   BEGIN
     FOR stream_rec IN
       SELECT DISTINCT "streamDate"::date as sd
       FROM public."streamEvents"
       WHERE "streamDate"::date < CURRENT_DATE
       ORDER BY sd
     LOOP
       PERFORM public.compute_stream_stats(stream_rec.sd);
     END LOOP;
   END;
   $function$
;

CREATE OR REPLACE FUNCTION public.compute_stream_stats(target_date date)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
   DECLARE
     v_total_events integer;
     v_total_chats integer;
     v_unique_chatters integer;
     v_unique_viewers integer;
     v_total_subs integer;
     v_total_giftsubs integer;
     v_total_giftsub_count integer;
     v_total_cheers integer;
     v_total_cheer_bits integer;
     v_total_raids integer;
     v_total_raid_viewers integer;
     v_total_follows integer;
   BEGIN
     -- Count total events (excluding join/part)
     SELECT COUNT(*) INTO v_total_events
     FROM public."streamEvents"
     WHERE "streamDate" = target_date::text
       AND "eventType" NOT IN ('onJoin', 'onPart');

     -- Count chats
     SELECT COUNT(*) INTO v_total_chats
     FROM public."streamEvents"
     WHERE "streamDate" = target_date::text
       AND "eventType" = 'onChatMessage';

     -- Count unique chatters
     SELECT COUNT(DISTINCT login) INTO v_unique_chatters
     FROM public."streamEvents"
     WHERE "streamDate" = target_date::text
       AND "eventType" = 'onChatMessage';

     -- Count unique viewers (from ANY event for that date)
     SELECT COUNT(DISTINCT login) INTO v_unique_viewers
     FROM public."streamEvents"
     WHERE "streamDate" = target_date::text;

     -- Count subs
     SELECT COUNT(*) INTO v_total_subs
     FROM public."streamEvents"
     WHERE "streamDate" = target_date::text
       AND "eventType" = 'twitch:sub';

     -- Count gift subs and total gifted
     SELECT COUNT(*), COALESCE(SUM(quantity), 0) INTO v_total_giftsubs,
  v_total_giftsub_count
     FROM public."streamEvents"
     WHERE "streamDate" = target_date::text
       AND "eventType" = 'twitch:giftsub';

     -- Count cheers and total bits
     SELECT COUNT(*), COALESCE(SUM(quantity), 0) INTO v_total_cheers, v_total_cheer_bits
     FROM public."streamEvents"
     WHERE "streamDate" = target_date::text
       AND "eventType" = 'twitch:cheer';

     -- Count raids and total viewers
     SELECT COUNT(*), COALESCE(SUM(quantity), 0) INTO v_total_raids,
  v_total_raid_viewers
     FROM public."streamEvents"
     WHERE "streamDate" = target_date::text
       AND "eventType" = 'twitch:raid';

     -- Count follows
     SELECT COUNT(*) INTO v_total_follows
     FROM public."streamEvents"
     WHERE "streamDate" = target_date::text
       AND "eventType" = 'twitch:follow';

     -- Upsert the stats
     INSERT INTO public.streams (
       stream_date, updated_at, total_events, total_chats, unique_chatters,
  unique_viewers,
       total_subs, total_giftsubs, total_giftsub_count, total_cheers, total_cheer_bits,
       total_raids, total_raid_viewers, total_follows
     ) VALUES (
       target_date, now(), v_total_events, v_total_chats, v_unique_chatters,
  v_unique_viewers,
       v_total_subs, v_total_giftsubs, v_total_giftsub_count, v_total_cheers,
  v_total_cheer_bits,
       v_total_raids, v_total_raid_viewers, v_total_follows
     )
     ON CONFLICT (stream_date) DO UPDATE SET
       updated_at = now(),
       total_events = EXCLUDED.total_events,
       total_chats = EXCLUDED.total_chats,
       unique_chatters = EXCLUDED.unique_chatters,
       unique_viewers = EXCLUDED.unique_viewers,
       total_subs = EXCLUDED.total_subs,
       total_giftsubs = EXCLUDED.total_giftsubs,
       total_giftsub_count = EXCLUDED.total_giftsub_count,
       total_cheers = EXCLUDED.total_cheers,
       total_cheer_bits = EXCLUDED.total_cheer_bits,
       total_raids = EXCLUDED.total_raids,
       total_raid_viewers = EXCLUDED.total_raid_viewers,
       total_follows = EXCLUDED.total_follows;
   END;
   $function$
;

