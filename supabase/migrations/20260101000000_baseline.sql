CREATE OR REPLACE FUNCTION public.get_analytics_summary(start_date timestamp with time zone, end_date timestamp with time zone, filter_domain text DEFAULT NULL::text, filter_browser text DEFAULT NULL::text, filter_device text DEFAULT NULL::text, filter_path text DEFAULT NULL::text, filter_referrer text DEFAULT NULL::text, filter_utm_source text DEFAULT NULL::text, filter_utm_medium text DEFAULT NULL::text, filter_utm_campaign text DEFAULT NULL::text, filter_utm_content text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$
DECLARE
  result jsonb;
BEGIN
  WITH filtered AS (
    SELECT *
    FROM "analytics_events"
    WHERE created_at >= start_date
      AND created_at <= end_date
      AND domain NOT ILIKE '%netlify.app%'
      AND domain NOT ILIKE '%localhost%'
      AND path NOT ILIKE '%wp-%'
      AND path NOT ILIKE '%xmlrpc%'
      AND path NOT ILIKE '%sitemap%'
      AND path NOT ILIKE '%/admin%'
      AND path NOT ILIKE '%/user%'
      AND path NOT ILIKE '%.json'
      AND path NOT ILIKE '%.txt'
      AND path NOT ILIKE '%.php'
      AND path NOT ILIKE '%.ico'
      AND path NOT ILIKE '%.png'
      AND path NOT ILIKE '%.jpg'
      AND path NOT ILIKE '%.jpeg'
      AND path NOT ILIKE '%.gif'
      AND path NOT ILIKE '%.svg'
      AND path NOT ILIKE '%.css'
      AND path NOT ILIKE '%.js'
      AND path NOT ILIKE '%.webp'
      AND path NOT ILIKE '%.woff%'
      AND path NOT ILIKE '%.xml'
      AND path != '/login'
      AND path != '/.env'
      AND (filter_domain IS NULL OR domain = filter_domain)
      AND (filter_browser IS NULL OR browser = filter_browser)
      AND (filter_device IS NULL OR device_type = filter_device)
      AND (filter_path IS NULL OR path = filter_path)
      AND (filter_referrer IS NULL OR
        CASE
          WHEN filter_referrer = 'Direct' THEN (referrer IS NULL OR referrer = '')
          ELSE (
            CASE
              WHEN referrer ~ '^https?://' THEN split_part(split_part(referrer, '://', 2), '/', 1)
              ELSE referrer
            END
          ) = filter_referrer
        END
      )
      AND (filter_utm_source IS NULL OR utm_source = filter_utm_source)
      AND (filter_utm_medium IS NULL OR utm_medium = filter_utm_medium)
      AND (filter_utm_campaign IS NULL OR utm_campaign = filter_utm_campaign)
      AND (filter_utm_content IS NULL OR utm_content = filter_utm_content)
  ),
  summary AS (
    SELECT
      count(*)::int AS total_views,
      count(DISTINCT session_id)::int AS unique_sessions
    FROM filtered
  ),
  top_browser AS (
    SELECT browser AS name, count(*)::int AS cnt
    FROM filtered
    GROUP BY browser
    ORDER BY cnt DESC
    LIMIT 1
  ),
  top_utm AS (
    SELECT utm_source AS name, count(*)::int AS cnt
    FROM filtered
    WHERE utm_source IS NOT NULL
    GROUP BY utm_source
    ORDER BY cnt DESC
    LIMIT 1
  ),
  top_pages AS (
    SELECT jsonb_agg(row_to_json(t)::jsonb ORDER BY t.cnt DESC) AS data
    FROM (
      SELECT path, count(*)::int AS cnt,
        mode() WITHIN GROUP (ORDER BY utm_medium) AS top_medium
      FROM filtered
      GROUP BY path
      ORDER BY cnt DESC
      LIMIT 10
    ) t
  ),
  referrer_data AS (
    SELECT jsonb_agg(row_to_json(t)::jsonb ORDER BY t.cnt DESC) AS data
    FROM (
      SELECT
        CASE
          WHEN referrer IS NULL OR referrer = '' THEN ''
          ELSE (
            CASE
              WHEN referrer ~ '^https?://' THEN split_part(split_part(referrer,
'://', 2), '/', 1)
              ELSE referrer
            END
          )
        END AS referrer,
        count(*)::int AS cnt
      FROM filtered
      GROUP BY 1
      ORDER BY cnt DESC
      LIMIT 10
    ) t
  ),
  browser_data AS (
    SELECT jsonb_agg(row_to_json(t)::jsonb ORDER BY t.cnt DESC) AS data
    FROM (
      SELECT COALESCE(browser, 'Unknown') AS name, count(*)::int AS cnt
      FROM filtered
      GROUP BY 1
      ORDER BY cnt DESC
      LIMIT 5
    ) t
  ),
  device_data AS (
    SELECT jsonb_agg(row_to_json(t)::jsonb ORDER BY t.cnt DESC) AS data
    FROM (
      SELECT COALESCE(device_type, 'unknown') AS name, count(*)::int AS cnt
      FROM filtered
      GROUP BY 1
      ORDER BY cnt DESC
    ) t
  ),
  utm_source_data AS (
    SELECT jsonb_agg(row_to_json(t)::jsonb ORDER BY t.cnt DESC) AS data
    FROM (
      SELECT utm_source AS name, count(*)::int AS cnt
      FROM filtered
      WHERE utm_source IS NOT NULL
      GROUP BY utm_source
      ORDER BY cnt DESC
      LIMIT 10
    ) t
  ),
  utm_medium_data AS (
    SELECT jsonb_agg(row_to_json(t)::jsonb ORDER BY t.cnt DESC) AS data
    FROM (
      SELECT utm_medium AS name, count(*)::int AS cnt
      FROM filtered
      WHERE utm_medium IS NOT NULL
      GROUP BY utm_medium
      ORDER BY cnt DESC
      LIMIT 10
    ) t
  ),
  utm_campaign_data AS (
    SELECT jsonb_agg(row_to_json(t)::jsonb ORDER BY t.cnt DESC) AS data
    FROM (
      SELECT utm_campaign AS name, count(*)::int AS cnt
      FROM filtered
      WHERE utm_campaign IS NOT NULL
      GROUP BY utm_campaign
      ORDER BY cnt DESC
      LIMIT 10
    ) t
  ),
  utm_content_data AS (
    SELECT jsonb_agg(row_to_json(t)::jsonb ORDER BY t.cnt DESC) AS data
    FROM (
      SELECT utm_content AS name, count(*)::int AS cnt
      FROM filtered
      WHERE utm_content IS NOT NULL
      GROUP BY utm_content
      ORDER BY cnt DESC
      LIMIT 10
    ) t
  ),
  daily_data AS (
    SELECT jsonb_agg(row_to_json(t)::jsonb ORDER BY t.period) AS data
    FROM (
      SELECT created_at::date::text AS period, count(*)::int AS cnt
      FROM filtered
      GROUP BY 1
      ORDER BY 1
    ) t
  )
  SELECT jsonb_build_object(
    'total_views', s.total_views,
    'unique_sessions', s.unique_sessions,
    'top_browser', (SELECT name FROM top_browser),
    'top_utm_source', (SELECT name FROM top_utm),
    'top_pages', COALESCE((SELECT data FROM top_pages), '[]'::jsonb),
    'referrers', COALESCE((SELECT data FROM referrer_data), '[]'::jsonb),
    'browsers', COALESCE((SELECT data FROM browser_data), '[]'::jsonb),
    'devices', COALESCE((SELECT data FROM device_data), '[]'::jsonb),
    'utm_sources', COALESCE((SELECT data FROM utm_source_data), '[]'::jsonb),
    'utm_mediums', COALESCE((SELECT data FROM utm_medium_data), '[]'::jsonb),
    'utm_campaigns', COALESCE((SELECT data FROM utm_campaign_data), '[]'::jsonb),
    'utm_content', COALESCE((SELECT data FROM utm_content_data), '[]'::jsonb),
    'daily_views', COALESCE((SELECT data FROM daily_data), '[]'::jsonb)
  ) INTO result
  FROM summary s;

  RETURN result;
END;
$function$
;

